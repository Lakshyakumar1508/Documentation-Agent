"""GitHub App integration with HMAC signature verification, App JWT auth, and PR creation."""

from datetime import datetime, timezone
import hashlib
import hmac
import time
from typing import Any, Dict, List, Optional
import jwt

from docagent.analyzer.models import BreakingChange
from docagent.core.config import settings
from docagent.core.exceptions import WebhookVerificationError
from docagent.core.logging import logger
from docagent.generator.models import DocProposal


class GitHubAppClient:
    """Manages GitHub App authentication, webhook signature checks, and PR generation."""

    def __init__(
        self,
        app_id: Optional[str] = None,
        private_key: Optional[str] = None,
        webhook_secret: Optional[str] = None,
    ):
        self.app_id = app_id or settings.GITHUB_APP_ID
        self.private_key = private_key or settings.GITHUB_APP_PRIVATE_KEY
        self.webhook_secret = webhook_secret or settings.GITHUB_WEBHOOK_SECRET
        self._processed_events: set = set()

    def verify_webhook_signature(self, payload_bytes: bytes, signature_header: Optional[str]) -> bool:
        """
        Verifies HMAC-SHA256 signature from GitHub webhook header (X-Hub-Signature-256).
        
        Args:
            payload_bytes: Raw request body.
            signature_header: Header value format: 'sha256=<hex_digest>'
            
        Raises:
            WebhookVerificationError: If header is missing or signature mismatch.
        """
        secret = self.webhook_secret or settings.GITHUB_WEBHOOK_SECRET
        if not secret:
            logger.warning("GITHUB_WEBHOOK_SECRET is not configured. Rejecting webhook request.")
            raise WebhookVerificationError("Webhook secret not configured on server.")

        if not signature_header:
            raise WebhookVerificationError("Missing X-Hub-Signature-256 header.")

        expected_sig = "sha256=" + hmac.new(
            secret.encode("utf-8"),
            payload_bytes,
            hashlib.sha256
        ).hexdigest()

        if not hmac.compare_digest(expected_sig, signature_header):
            raise WebhookVerificationError("Invalid webhook signature.")

        return True

    def is_duplicate_event(self, delivery_id: str) -> bool:
        """Checks if delivery ID has already been handled (idempotency guard)."""
        if delivery_id in self._processed_events:
            return True
        self._processed_events.add(delivery_id)
        return False

    def generate_app_jwt(self) -> str:
        """Generates RS256 signed JWT for GitHub App authentication."""
        if not self.app_id or not self.private_key:
            raise ValueError("Both GITHUB_APP_ID and GITHUB_APP_PRIVATE_KEY are required to generate JWT.")

        now = int(time.time())
        payload = {
            "iat": now - 60,       # 1 minute clock skew allowance
            "exp": now + (10 * 60), # 10 minutes validity
            "iss": self.app_id,
        }
        encoded_jwt = jwt.encode(payload, self.private_key, algorithm="RS256")
        return encoded_jwt

    @staticmethod
    def format_pull_request_body(
        proposals: List[DocProposal],
        breaking_changes: Optional[List[BreakingChange]] = None,
        commit_sha: Optional[str] = None
    ) -> str:
        """Generates Markdown Pull Request description with structured evidence table."""
        lines = [
            "## 🤖 Automated Documentation Maintenance Update",
            "",
            "This Pull Request was generated by **DocAgent** based on static code inventory analysis and verified Git changes.",
            "",
            f"- **Grounding Commit**: `{commit_sha or 'HEAD'}`",
            f"- **Generated At**: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}",
            "",
            "### 📄 Proposed Documentation Changes",
            "| File Path | Document Type | Action | Evidence Anchors |",
            "| :--- | :--- | :--- | :--- |",
        ]

        for p in proposals:
            action = "Created" if p.is_new_file else "Updated"
            anchors_count = len(p.evidence_anchors)
            lines.append(f"| `{p.file_path}` | `{p.doc_type.value}` | {action} | {anchors_count} anchors |")

        if breaking_changes:
            lines.extend([
                "",
                "### ⚠️ Detected Breaking API Changes",
                "| Severity | Symbol / Route | File | Details |",
                "| :--- | :--- | :--- | :--- |",
            ])
            for b in breaking_changes:
                lines.append(f"| `{b.severity.upper()}` | `{b.symbol_name}` | `{b.file_path}` | {b.description} |")

        lines.extend([
            "",
            "### 🔒 Quality & Security Verification",
            "- [x] Secret redaction applied to all log and code excerpts.",
            "- [x] AST symbol claims cross-referenced against codebase.",
            "- [x] Zero repository code executed during analysis.",
            "",
            "> [!NOTE]",
            "> Please review the proposed unified diffs before merging. To accept changes, approve and merge this PR.",
        ])

        return "\n".join(lines)
